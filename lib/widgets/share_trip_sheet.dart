import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:share_plus/share_plus.dart';
import 'package:url_launcher/url_launcher.dart';

class ShareTripSheet extends StatelessWidget {
  final String title;
  final int budget;
  final int people;
  final String duration;

  String get shareText => '''
🧭 Trip: $title
💰 Budget: $budget JD
👥 Group: $people people
🕒 Duration: $duration
📍 Includes transport + full itinerary

Generated by Jordan Smart Trip AI
''';

  const ShareTripSheet({
    super.key,
    required this.title,
    required this.budget,
    required this.people,
    required this.duration,
  });

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(22),
      decoration: const BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.vertical(
          top: Radius.circular(28),
        ),
      ),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [

          Container(
            width: 45,
            height: 5,
            decoration: BoxDecoration(
              color: Colors.grey.shade300,
              borderRadius: BorderRadius.circular(20),
            ),
          ),

          const SizedBox(height: 18),

          const Text(
            "Share Trip",
            style: TextStyle(
              fontSize: 22,
              fontWeight: FontWeight.bold,
            ),
          ),

          const SizedBox(height: 18),

          Container(
            width: double.infinity,
            padding: const EdgeInsets.all(18),
            decoration: BoxDecoration(
              color: const Color(0xFFF3F4F6),
              borderRadius: BorderRadius.circular(18),
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [

                const Text(
                  "Trip Summary",
                  style: TextStyle(
                    fontWeight: FontWeight.bold,
                  ),
                ),

                const SizedBox(height: 12),

                Text("🧭 Trip: $title"),
                Text("💰 Budget: $budget JD"),
                Text("👥 Group: $people people"),
                Text("🕒 Duration: $duration"),
                const Text("📍 Includes transport + full itinerary"),

                const SizedBox(height: 14),

                const Text(
                  "Generated by Jordan Smart Trip AI",
                  style: TextStyle(
                    color: Colors.grey,
                    fontSize: 12,
                  ),
                ),
              ],
            ),
          ),

          const SizedBox(height: 20),

          SizedBox(
            width: double.infinity,
            height: 52,
            child: ElevatedButton.icon(
             onPressed: () async {
              final url = Uri.parse(
                "https://wa.me/?text=${Uri.encodeComponent(shareText)}",
              );

              await launchUrl(url, mode: LaunchMode.externalApplication);
            },
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF25D366),
              ),
              icon: const Icon(Icons.message),
              label: const Text("Share via WhatsApp"),
            ),
          ),

          const SizedBox(height: 12),

          SizedBox(
            width: double.infinity,
            height: 52,
            child: OutlinedButton.icon(
              onPressed: () async {
                await Clipboard.setData(
                  ClipboardData(text: shareText),
                );

                ScaffoldMessenger.of(context).showSnackBar(
                  const SnackBar(
                    content: Text("Copied to clipboard"),
                  ),
                );
              },
              icon: const Icon(Icons.link),
              label: const Text("Copy Shareable Link"),
            ),
          ),
        ],
      ),
    );
  }
}